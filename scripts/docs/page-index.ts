import { metadataOf, routeOf } from "./pages";
import type { RepoSource } from "./source";

/**
 * Every signed-in page that has a fixed address and a title, as data the header
 * search can read. Derived from the same `page.tsx` files and the same
 * `metadata` the pages inventory is, so there is one reading of "what pages
 * exist" and a page cannot be searchable without being listed, or listed
 * without being searchable.
 *
 * Left out on purpose: a route with a parameter (it is a record, not a place),
 * a page with no stated title (nothing to show), and the ones in `EXCLUDED`,
 * which are finishing steps nobody goes looking for.
 */
export type IndexedPage = { href: string; title: string; description: string };

const EXCLUDED = new Set([
  "/[...rest]",
  "/settings/integrations/connect-return",
]);

export function buildPageIndex(source: RepoSource): IndexedPage[] {
  const pages: IndexedPage[] = [];
  for (const file of source.files()) {
    if (!/^src\/app\/\(app\)\/(.*\/)?page\.tsx$/.test(file)) continue;
    const { route } = routeOf(file);
    if (route.includes("[") || EXCLUDED.has(route)) continue;
    const { title, description } = metadataOf(source.read(file));
    if (!title) continue;
    pages.push({ href: route, title, description: description ?? "" });
  }
  return pages.sort((a, b) => (a.href < b.href ? -1 : 1));
}

export function pageIndexModule(pages: readonly IndexedPage[]): string {
  return `// Generated by \`npm run docs\` from every page's own metadata. Do not edit:
// re-run the generator. Read by the header search (\`command-palette.tsx\`).
export const PAGE_INDEX: readonly { href: string; title: string; description: string }[] = ${JSON.stringify(pages, null, 2)};
`;
}
