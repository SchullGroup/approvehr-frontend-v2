/**
 * Imports the Open Peeps figures the app draws (docs/illustrations.md says which, where and why).
 *
 *     npx tsx scripts/import-peeps.ts "<path to the unzipped 'Flat Assets' folder>"
 *
 * Open Peeps is by Pablo Stanley and is released under CC0, so nothing here needs a credit. The pack is the
 * "Open Peeps Flat Assets" zip linked from its Gumroad page; docs/illustrations.md has the address.
 *
 * What it does, in order, and nothing else:
 * 1. copies the chosen template SVGs to a temporary folder;
 * 2. runs svgo over them (through npx, so svgo is not a dependency of the app): one decimal of path
 *    precision, ids and metadata dropped. The files go from about 50 KB to about 10 KB each. The `xmlns` is
 *    KEPT: these are used as `<img src>`, and an SVG without it does not draw there;
 * 3. crops each file's view box to where the drawing actually is (`INK`), and writes it to
 *    `public/illustrations/peeps/<name>.svg`;
 * 4. writes `src/lib/peeps.ts`, the name list and each figure's shape, which `Illustration` reads.
 *
 * The figures keep Open Peeps' own colours (white fill, black line) on purpose: they are never recoloured.
 * The same figures, with the same names, are in the mobile app (`approvehr-mobile`, `src/ui/art`).
 */
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/** name, and where it comes from in the pack. */
const FIGURES: { name: string; from: string }[] = [
  { name: "hand-on-hip", from: "Standing/peep-standing-9.svg" },
  { name: "shrug", from: "Bust/peep-71.svg" },
  { name: "coffee-break", from: "Bust/peep-59.svg" },
  { name: "on-phone", from: "Bust/peep-45.svg" },
  { name: "arms-crossed", from: "Bust/peep-66.svg" },
  { name: "paper-b", from: "Bust/peep-67.svg" },
  { name: "welcome", from: "Bust/peep-57.svg" },
];

/**
 * Where the drawing actually is, inside each template's artboard: x, y, width, height, measured once with
 * `getBBox()` in a browser on the optimised files. The pack's artboards leave blank margins around most figures
 * (about 40 units above and below a bust), so drawing the whole artboard shows empty space. Re-measure if the
 * figures or the svgo settings change.
 */
const INK: Record<string, readonly [number, number, number, number]> = {
  "hand-on-hip": [0, 0.2, 248.5, 671.1],
  shrug: [12.3, 42.9, 246.1, 237.1],
  "coffee-break": [36.2, 40.6, 165.3, 242.6],
  "on-phone": [41.1, 39.7, 157.8, 244.5],
  "arms-crossed": [40, 32.1, 168.8, 258],
  "paper-b": [38.4, 50.3, 163.3, 235],
  welcome: [40.8, 29.1, 154.3, 253.4],
};

const SVGO_CONFIG = `module.exports = {
  multipass: true,
  floatPrecision: 1,
  plugins: ["preset-default", "removeTitle", "removeDimensions"],
};
`;

function main() {
  const pack = process.argv[2];
  if (!pack) {
    console.error(
      "Usage: npx tsx scripts/import-peeps.ts <path to the 'Flat Assets' folder>",
    );
    process.exit(1);
  }
  const work = mkdtempSync(join(tmpdir(), "peeps-"));
  const input = join(work, "in");
  const output = join(work, "out");
  mkdirSync(input);
  mkdirSync(output);
  for (const f of FIGURES) {
    copyFileSync(join(pack, "Templates", f.from), join(input, `${f.name}.svg`));
  }
  const config = join(work, "svgo.config.cjs");
  writeFileSync(config, SVGO_CONFIG);
  execFileSync(
    "npx",
    [
      "--yes",
      "svgo@4",
      "--config",
      config,
      "-f",
      input,
      "-o",
      output,
      "--quiet",
    ],
    { stdio: "inherit" },
  );

  const target = join(process.cwd(), "public/illustrations/peeps");
  mkdirSync(target, { recursive: true });
  const rows: string[] = [];
  for (const f of FIGURES) {
    const box = INK[f.name];
    if (!box) throw new Error(`${f.name}: no ink bounds in INK`);
    let svg = readFileSync(join(output, `${f.name}.svg`), "utf8");
    if (!/viewBox="[^"]*"/.test(svg)) throw new Error(`${f.name}: no viewBox`);
    if (!svg.includes("xmlns=")) throw new Error(`${f.name}: lost its xmlns`);
    svg = svg.replace(/viewBox="[^"]*"/, `viewBox="${box.join(" ")}"`);
    writeFileSync(join(target, `${f.name}.svg`), svg);
    rows.push(`  "${f.name}": [${box[2]}, ${box[3]}],`);
  }
  const registry = `// Generated by scripts/import-peeps.ts. Do not edit by hand.
// Open Peeps by Pablo Stanley, CC0. The files are in public/illustrations/peeps/.

/** Each figure's drawn width and height, in the units of its own view box: only the shape matters. */
export const PEEPS = {
${rows.join("\n")}
} as const satisfies Record<string, readonly [number, number]>;

export type PeepName = keyof typeof PEEPS;
`;
  writeFileSync(join(process.cwd(), "src/lib/peeps.ts"), registry);
  // The repo's format check is strict about quoting; let prettier have the last word on the generated file.
  execFileSync("npx", ["prettier", "--write", "src/lib/peeps.ts"], {
    stdio: "inherit",
  });
  console.log(`Wrote ${FIGURES.length} figures to public/illustrations/peeps/`);
}

main();
