/**
 * Payroll runs, from whichever source is available.
 *
 * Connected → `/api/v1/payroll`. Demo → a run computed here, in this browser.
 * Every screen calls these hooks and does not care which it got; `connected`
 * comes back on every result so the screen can say which one it is showing.
 *
 * ## The demo run is computed, not written down
 *
 * A draft run's figures are **recomputed from the live employee directory on
 * every render**. That is not laziness — it is the property the product is
 * selling. Fix a missing account number on somebody's record and the blocker
 * clears here without a reload, exactly as it does against the API, because in
 * both modes the run is a function of the directory rather than a copy of it.
 *
 * Approval is where that stops. An approved run carries a **frozen** snapshot,
 * and from then on the figures come out of the snapshot no matter what the
 * directory says afterwards. That is the same one-way door the API implements,
 * for the same reason: a payslip from 2026 has to explain itself in 2029, and
 * re-deriving it from tomorrow's records would silently rewrite it.
 *
 * ## Where the demo’s figures come from, now that there is no second engine
 *
 * There used to be a copy of the payroll engine in this browser, and demo runs
 * were computed with it. It was left on the 2011 PAYE bands when the Nigeria Tax
 * Act 2025 went into the API, so it quoted last year’s tax for a while. It is
 * deleted, and nothing here computes statutory anything.
 *
 * Demo payslips now read **fixed illustrative figures** from
 * `lib/mock/demo-payslips.ts`, generated by the API’s own engine for the demo
 * directory’s salaries and labelled illustrative on every screen that shows
 * them. A payroll product whose payroll module shows nothing without a database
 * cannot be demonstrated, and a second implementation of tax law is what we just
 * finished removing — fixed output is the third option, and the only honest one.
 *
 * Two things make the fixture refuse rather than mislead, both as BLOCKERs on
 * the run:
 *
 * - **A salary it has no row for.** Edit somebody’s pay in demo mode, or create
 *   a person, and there is no figure to show. `payslipFiguresFor` returns null
 *   and the run names them.
 * - **Settings changed away from the demo defaults.** The figures were generated
 *   on one set of rates. Change a pension rate and they no longer describe what
 *   this company pays, so they are withheld rather than relabelled.
 *
 * ## What the demo deliberately does not do
 *
 * - **No allowances.** The fixture is the plainest possible payslip — contract
 *   salary, statutory deductions, nothing else. Allowances need the API, and the
 *   screens say so.
 * - **No proration.** Unpaid days come from the attendance roster, which the
 *   demo run does not read. Every demo payslip is a full month.
 * - **Nothing statutory.** Post-tax deductions are applied on top of the
 *   fixture, which is exact integer arithmetic and needs no engine: an after-tax
 *   deduction takes exactly its own amount off take-home, capped at what is
 *   there.
 *
 * ## Exclusions work in demo mode, and that is a decision
 *
 * `store/departments.ts` refuses every write offline, because a department is a
 * payroll reporting boundary and a tree built in one browser would never reach a
 * run — building one would teach the opposite of how the product works.
 * `store/shifts.ts` argues the other way for the rota, because nothing else in
 * the frontend reads it. **An exclusion is the shifts case, not the departments
 * case**: it is one run's decision about one person, it lives in the same
 * persisted record as the run it belongs to, and nothing outside these hooks
 * reads it. So the demo can show the whole loop — blocker, exclude with a reason,
 * recalculate, approve — which is the loop the feature exists for and the thing a
 * buyer needs to watch happen.
 *
 * It behaves like the API in the two ways that matter. The blocker **stays** a
 * blocker until somebody excludes that person, so the safe outcome is the one you
 * get by doing nothing. And the exclusion is keyed to the period, so preparing
 * the next month brings them back with nothing to remember.
 */

