/**
 * One run in full, with its payslips and open exceptions.
 *
 * Kept as `{ id, nonce, detail }` rather than a bare detail so the result
 * carries the request it belongs to. `loading` is then derived during render
 * instead of tracked, which means there is nothing to clear when `id` changes
 * and no window where the previous run's figures are shown as though they were
 * this one's. Clearing it in an effect would be a setState in an effect body.
 */
export function usePayrollRun(id: string | null): RunState {
  const { isConnected } = useSession();
  const demo = useDemoContext();
  const [nonce, setNonce] = useState(0);
  const [fetched, setFetched] = useState<{
    id: string;
    nonce: number;
    detail: PayrollRunDetail | null;
    error: ApiError | null;
  } | null>(null);

  const active = isConnected && Boolean(id);

  /* Re-ask when somebody comes back to the window. Not in the key below,
     so the answer is replaced without the screen flashing a skeleton. */
  const revalidation = useRevalidation();
  useEffect(() => {
    if (!active || !id) return;
    let cancelled = false;
    const controller = new AbortController();
    void (async () => {
      try {
        const detail = await payrollApi.run(id, controller.signal);
        if (!cancelled) setFetched({ id, nonce, detail, error: null });
      } catch (error) {
        if (error instanceof DOMException && error.name === "AbortError")
          return;
        if (!cancelled) {
          setFetched({
            id,
            nonce,
            detail: null,
            error: error instanceof ApiError ? error : null,
          });
        }
      }
    })();
    return () => {
      cancelled = true;
      controller.abort();
    };
  }, [active, id, nonce, revalidation]);

  const reload = useCallback(() => setNonce((n) => n + 1), []);

  if (!isConnected) {
    const run = id ? (demo.details.find((d) => d.id === id) ?? null) : null;
    return {
      run,
      loading: false,
      error: null,
      connected: false,
      notFound: Boolean(id) && run === null,
      reload: () => {},
    };
  }

  const matched =
    active && fetched !== null && fetched.id === id && fetched.nonce === nonce;
  return {
    run: matched ? fetched.detail : null,
    loading: active && !matched,
    error: matched ? fetched.error : null,
    connected: true,
    notFound: matched && fetched.error?.status === 404,
    reload,
  };
}

/**
 * One run's payslips, filtered, sorted and paged by the API.
 *
 * ## Why the distribution table stopped reading `usePayrollRun`
 *
 * `usePayrollRun` returns the run with **every** payslip nested. The payslip
 * index took that array, sorted it, filtered it and counted it, and put three
 * figures above the table: total, not sent, opened. For a company of two thousand
 * that response is megabytes, the counts describe the array rather than the
 * payroll, and the sort is over whatever the API happened to send.
 *
 * `GET /payroll/runs/:id/payslips` answers the counts alongside the page, so
 * "Not sent: 1,974" is a `count` query rather than a `filter().length`.
 *
 * ## Demo mode pages and counts the fixture the same way
 *
 * The demo run holds its payslips in the persisted record, so filtering them
 * locally is not a lie — there is no larger set behind them. What it must still
 * do is **count before it cuts**, which is the habit the connected path depends
 * on: a demo that reported the page length would let a screen ship a bug that
 * only appears against a database.
 */
export type RunPayslipsState = {
  payslips: Payslip[];
  /** The server's count under this filter. `undefined` until it answers. */
  total: number | undefined;
  /** How many are in each delivery state across the whole run, from the server. */
  counts: PayslipCounts | undefined;
  loading: boolean;
  error: ApiError | null;
  connected: boolean;
};

/** Which of the three delivery states a payslip is in. */
export const deliveryOf = (slip: Payslip): PayslipDelivery =>
  slip.viewedAt ? "opened" : slip.emailedAt ? "sent" : "not_sent";

export function useRunPayslips(
  runId: string | null,
  params: PayslipListParams = {},
): RunPayslipsState {
  const { isConnected } = useSession();
  const demo = useDemoContext();

  const key = JSON.stringify(params);
  const active = isConnected && Boolean(runId);

  const [fetched, setFetched] = useState<{
    runId: string;
    key: string;
    page: PayslipPage | null;
    error: ApiError | null;
  } | null>(null);

  /* Re-ask when somebody comes back to the window. Not in the key below,
     so the answer is replaced without the screen flashing a skeleton. */
  const revalidation = useRevalidation();
  useEffect(() => {
    if (!active || !runId) return;
    let cancelled = false;
    const controller = new AbortController();

    void (async () => {
      try {
        const page = await payrollApi.payslips(
          runId,
          JSON.parse(key) as PayslipListParams,
          controller.signal,
        );
        if (!cancelled) setFetched({ runId, key, page, error: null });
      } catch (error) {
        if (error instanceof DOMException && error.name === "AbortError")
          return;
        if (!cancelled) {
          setFetched({
            runId,
            key,
            page: null,
            error: error instanceof ApiError ? error : null,
          });
        }
      }
    })();

    return () => {
      cancelled = true;
      controller.abort();
    };
  }, [active, runId, key, revalidation]);

  /* The demo answer, computed in a `useMemo` that touches no state — the shape
     `lib/store/shifts.ts` establishes and every store in this app follows. */
  const local = useMemo(() => {
    if (isConnected) return null;
    const run = runId
      ? demo.details.find((detail) => detail.id === runId)
      : null;
    if (!run) {
      return {
        payslips: [] as Payslip[],
        total: 0,
        counts: { notSent: 0, sent: 0, opened: 0 },
      };
    }
    const parsed = JSON.parse(key) as PayslipListParams;

    const searched = parsed.q
      ? run.payslips.filter((slip) =>
          [slip.name, slip.employeeNo].some((field) =>
            field.toLowerCase().includes(parsed.q!.toLowerCase()),
          ),
        )
      : run.payslips;

    /* The three counts are over the searched set and **not** the delivery
       filter, exactly as the API computes them: they are the counts beside the
       filter, so they have to say what is behind the option you are not on. */
    const counts = {
      notSent: searched.filter((s) => deliveryOf(s) === "not_sent").length,
      sent: searched.filter((s) => deliveryOf(s) === "sent").length,
      opened: searched.filter((s) => deliveryOf(s) === "opened").length,
    };

    const matched = parsed.delivery
      ? searched.filter((slip) => deliveryOf(slip) === parsed.delivery)
      : searched;

    const sorted = sortPayslips(matched, parsed);
    const size = parsed.pageSize ?? 25;
    const start = ((parsed.page ?? 1) - 1) * size;

    return {
      payslips: sorted.slice(start, start + size),
      total: matched.length,
      counts,
    };
  }, [isConnected, runId, key, demo.details]);

  if (local) {
    return { ...local, loading: false, error: null, connected: false };
  }

  const matched =
    active &&
    fetched !== null &&
    fetched.runId === runId &&
    fetched.key === key;

  return {
    payslips: matched ? (fetched.page?.payslips ?? []) : [],
    total: matched ? fetched.page?.total : undefined,
    counts: matched ? fetched.page?.counts : undefined,
    loading: active && !matched,
    error: matched ? fetched.error : null,
    connected: true,
  };
}

/**
 * The demo's copy of the API's payslip order — **with the tiebreaker**.
 *
 * `id` last for the same reason the API does it. Sorting two thousand payslips by
 * net pay, where every intern ties on the same figure, otherwise puts somebody on
 * two pages and somebody else on none.
 */
function sortPayslips(rows: Payslip[], params: PayslipListParams): Payslip[] {
  const dir = params.order === "desc" ? -1 : 1;

  const value = (slip: Payslip): string | number => {
    switch (params.sort) {
      case "employeeNo":
        return slip.employeeNo.toLowerCase();
      case "gross":
        return slip.grossKobo;
      case "net":
        return slip.netKobo;
      case "paye":
        return slip.payeKobo;
      case "emailedAt":
        return slip.emailedAt ?? "";
      case "viewedAt":
        return slip.viewedAt ?? "";
      default:
        return slip.name.toLowerCase();
    }
  };

  if (!params.sort) {
    /* No sort asked for: the queue. Not-yet-emailed first, then by name. */
    return [...rows].sort(
      (a, b) =>
        DELIVERY_RANK[deliveryOf(a)] - DELIVERY_RANK[deliveryOf(b)] ||
        a.name.localeCompare(b.name) ||
        a.id.localeCompare(b.id),
    );
  }

  return [...rows].sort((a, b) => {
    const left = value(a);
    const right = value(b);
    if (left < right) return -dir;
    if (left > right) return dir;
    return a.id < b.id ? -dir : a.id > b.id ? dir : 0;
  });
}

