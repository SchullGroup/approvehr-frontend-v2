/** What needs a human, first. */
const DELIVERY_RANK: Record<PayslipDelivery, number> = {
  not_sent: 0,
  sent: 1,
  opened: 2,
};

/**
 * Prepare, approve, cancel, exclude, put back.
 *
 * Each one refuses in demo mode only where the demo genuinely cannot do it,
 * and all of them do work locally — preparing a period, excluding the one person
 * whose record is incomplete, and approving it is the sequence the demo most
 * needs to be able to show.
 */
export function usePayrollActions() {
  const { isConnected, displayName } = useSession();
  const { directory } = useEmployeeStore();
  const settings = useDemoPayrollSettings();
  const people = useMemo(() => runPeopleFrom(directory), [directory]);

  const prepare = useCallback(
    async (input: {
      period: string;
      payDate: string;
      label?: string;
    }): Promise<PreparedRun> => {
      if (isConnected) return payrollApi.prepare(input);

      const state = demoStore.current();
      const existing = state.runs.find((r) => r.period === input.period);
      if (
        existing &&
        (existing.status === "APPROVED" || existing.status === "PAID")
      ) {
        throw new ApiError(
          409,
          "conflict",
          `The ${input.period} run is already approved. Cancel it before preparing that period again.`,
        );
      }
      if (people.length === 0) {
        throw new ApiError(
          422,
          "unprocessable",
          "Nobody is on the payroll for this period. Add employees first.",
        );
      }

      const record: DemoRunRecord = {
        period: input.period,
        payDate: input.payDate,
        label: input.label ?? null,
        status: "IN_REVIEW",
        preparedAt: new Date().toISOString(),
        approvedAt: null,
        /**
         * Carried over, never rebuilt.
         *
         * Preparing replaces the payslips and the exception list wholesale — on
         * the API and here. If it took the exclusions with them, excluding
         * somebody and pressing Calculate again would resurrect the blocker they
         * were excluded for and the loop would never end.
         */
        exclusions: existing ? exclusionsOf(existing) : [],
        frozen: null,
      };
      demoStore.commit({
        runs: [...state.runs.filter((r) => r.period !== input.period), record],
      });

      return preparedFrom(buildDemoRun(record, people, settings));
    },
    [isConnected, people, settings],
  );

  const approve = useCallback(
    async (runId: string): Promise<ApprovedRun> => {
      if (isConnected) return payrollApi.approve(runId);

      const state = demoStore.current();
      const record = state.runs.find((r) => demoRunId(r.period) === runId);
      if (!record) throw new ApiError(404, "not_found", "No such payroll run.");
      if (record.status === "APPROVED" || record.status === "PAID") {
        throw new ApiError(409, "conflict", "That run is already approved.");
      }

      const detail = buildDemoRun(record, people, settings);
      const blockers = detail.exceptions.filter(
        (e) => e.severity === "BLOCKER",
      );
      if (blockers.length > 0) {
        throw new ApiError(
          422,
          "unprocessable",
          `This run cannot be approved yet. ${blockers.map((b) => b.message).join(" ")}`,
        );
      }

      const approvedAt = new Date().toISOString();
      /* Frozen here and nowhere else. After this the figures no longer move
         when the directory does — which is the whole point of approving. */
      const frozen: PayrollRunDetail = {
        ...detail,
        status: "APPROVED",
        approvedAt,
        settingsFrozen: true,
        exceptions: detail.exceptions.filter((e) => e.severity === "WARNING"),
      };
      demoStore.commit({
        runs: state.runs.map((r) =>
          r.period === record.period
            ? { ...r, status: "APPROVED" as const, approvedAt, frozen }
            : r,
        ),
      });

      const settledLoans = detail.payslips.filter((p) =>
        p.lines.some((l) => l.kind === "DEDUCTION" && !l.taxable),
      ).length;
      return {
        id: runId,
        settled: { loans: settledLoans, claims: 0, overtime: 0 },
      };
    },
    [isConnected, people, settings],
  );

  const cancel = useCallback(
    async (runId: string): Promise<{ id: string }> => {
      if (isConnected) return payrollApi.cancel(runId);

      const state = demoStore.current();
      const record = state.runs.find((r) => demoRunId(r.period) === runId);
      if (!record) throw new ApiError(404, "not_found", "No such payroll run.");
      if (record.status === "PAID") {
        throw new ApiError(
          409,
          "conflict",
          "That run has been paid. A paid run is a record of money that moved and cannot be cancelled.",
        );
      }
      demoStore.commit({
        runs: state.runs.map((r) =>
          r.period === record.period
            ? { ...r, status: "CANCELLED" as const, frozen: null }
            : r,
        ),
      });
      return { id: runId };
    },
    [isConnected],
  );

  /**
   * Leaves somebody off this payroll, with the reason on the record.
   *
   * Rebuilds the period in both modes, and answers with the rebuilt figures —
   * because a run is a function of the directory and this run's exclusions, so
   * every total and both counts move the moment somebody is left off. A screen
   * that kept the old ones would show a payslip for somebody it says is not
   * being paid.
   */
  const exclude = useCallback(
    async (
      runId: string,
      input: { employeeId: string; reason: string },
    ): Promise<ExclusionChange> => {
      if (isConnected) return payrollApi.exclude(runId, input);

      const reason = input.reason.trim();
      if (reason.length < 4) {
        throw new ApiError(
          422,
          "unprocessable",
          "Say why they are not being paid this period. This is the only answer " +
            "anybody will have in a year's time.",
        );
      }

      const state = demoStore.current();
      const record = state.runs.find((r) => demoRunId(r.period) === runId);
      if (!record) throw new ApiError(404, "not_found", "No such payroll run.");
      if (record.status !== "DRAFT" && record.status !== "IN_REVIEW") {
        throw new ApiError(
          409,
          "conflict",
          `The ${record.period} payroll is ${record.status.toLowerCase()}. ` +
            "Who was on it is part of the record now and cannot be changed.",
        );
      }

      const person = people.find((p) => p.id === input.employeeId);
      if (!person) throw new ApiError(404, "not_found", "No such employee.");
      if (exclusionsOf(record).some((row) => row.employeeId === person.id)) {
        throw new ApiError(
          409,
          "conflict",
          `${person.name} is already excluded from the ${record.period} payroll. ` +
            "Put them back on it first if the reason has changed.",
        );
      }

      const excludedAt = new Date().toISOString();
      const next: DemoRunRecord = {
        ...record,
        exclusions: [
          ...exclusionsOf(record),
          { employeeId: person.id, reason, decidedBy: displayName, excludedAt },
        ],
      };
      demoStore.commit({
        runs: state.runs.map((r) => (r.period === record.period ? next : r)),
      });

      return {
        employeeId: person.id,
        name: person.name,
        reason,
        excludedAt,
        run: preparedFrom(buildDemoRun(next, people, settings)),
      };
    },
    [isConnected, people, settings, displayName],
  );

  /**
   * Puts somebody back on this payroll.
   *
   * The record is removed rather than marked withdrawn: it described this run and
   * this run alone, and the run now carries the truth — they have a payslip
   * again. Whatever originally blocked them comes back with them if it was never
   * fixed, which is the point. This does not pay anybody; it stops them being
   * skipped.
   */
  const putBack = useCallback(
    async (runId: string, employeeId: string): Promise<ExclusionChange> => {
      if (isConnected) return payrollApi.putBack(runId, employeeId);

      const state = demoStore.current();
      const record = state.runs.find((r) => demoRunId(r.period) === runId);
      if (!record) throw new ApiError(404, "not_found", "No such payroll run.");
      if (record.status !== "DRAFT" && record.status !== "IN_REVIEW") {
        throw new ApiError(
          409,
          "conflict",
          `The ${record.period} payroll is ${record.status.toLowerCase()}. ` +
            "Who was on it is part of the record now and cannot be changed.",
        );
      }

      const kept = exclusionsOf(record).filter(
        (row) => row.employeeId !== employeeId,
      );
      if (kept.length === exclusionsOf(record).length) {
        throw new ApiError(
          404,
          "not_found",
          "That person is not excluded from this payroll.",
        );
      }

      const next: DemoRunRecord = { ...record, exclusions: kept };
      demoStore.commit({
        runs: state.runs.map((r) => (r.period === record.period ? next : r)),
      });

      const person = people.find((p) => p.id === employeeId);
      return {
        employeeId,
        name: person?.name ?? "That person",
        run: preparedFrom(buildDemoRun(next, people, settings)),
      };
    },
    [isConnected, people, settings],
  );

  /**
   * Enters somebody's PAYE by hand for this one payroll, in place of the
   * engine's own bands, and rebuilds the period.
   *
   * **Refuses outright in demo mode.** Every other write here can be
   * reproduced locally because it only decides who is on the run — the figures
   * themselves still come from the one real engine, generated once into the
   * demo fixture. Recomputing a payslip's net pay around a hand-typed PAYE
   * figure needs that same engine, and this repo has exactly one, in the API.
   * Reimplementing tax-band arithmetic here to make this button work offline
   * is the mistake `HANDOVER.md` spends a whole section warning against.
   */
  /**
   * Overtime hours entered by hand. Refuses offline for the same reason the
   * tax override does: hours typed here would be valued against a policy and a
   * salary the demo has no engine to apply, and a figure nobody computed is a
   * figure nobody can vouch for.
   */
  const setOvertimeOverride = useCallback(
    async (
      runId: string,
      input: {
        employeeId: string;
        hours: number;
        kind: OvertimeOverrideKind;
        reason: string;
      },
    ): Promise<OvertimeOverrideChange> => {
      if (isConnected) return payrollApi.setOvertimeOverride(runId, input);
      throw new ApiError(
        0,
        "offline",
        "Entering overtime by hand needs the API. The hourly rate comes from " +
          "the company's policy and the person's salary, and the demo has no " +
          "engine to apply them, so it will not pretend it has.",
      );
    },
    [isConnected],
  );

  const clearOvertimeOverride = useCallback(
    async (runId: string, employeeId: string): Promise<PreparedRun> => {
      if (isConnected) return payrollApi.clearOvertimeOverride(runId, employeeId);
      throw new ApiError(
        0,
        "offline",
        "Entering overtime by hand needs the API, so there is nothing here for " +
          "the demo to clear.",
      );
    },
    [isConnected],
  );

  /** A one-off payment. Refuses offline for the same reason as the rest. */
  const setBonus = useCallback(
    async (
      runId: string,
      input: { employeeId: string; amountKobo: number; reason: string },
    ): Promise<BonusChange> => {
      if (isConnected) return payrollApi.setBonus(runId, input);
      throw new ApiError(
        0,
        "offline",
        "Adding a bonus needs the API. It moves gross and the tax on it, and " +
          "the demo has no engine to recompute either.",
      );
    },
    [isConnected],
  );

  const clearBonus = useCallback(
    async (runId: string, employeeId: string): Promise<PreparedRun> => {
      if (isConnected) return payrollApi.clearBonus(runId, employeeId);
      throw new ApiError(0, "offline", "Adding a bonus needs the API.");
    },
    [isConnected],
  );

  /**
   * Somebody's contractual monthly pay, from the payroll table.
   *
   * Refused offline, and for a stronger reason than the two overrides: this
   * writes the **employment record**. A salary changed in browser storage would
   * never reach a payroll run, and unlike a demo leave request it would look
   * exactly like a real pay rise on the screen that shows it.
   */
  const setMonthlyPay = useCallback(
    async (
      runId: string,
      input: { employeeId: string; grossMonthlyKobo: number; reason: string },
    ): Promise<MonthlyPayChange> => {
      if (isConnected) return payrollApi.setMonthlyPay(runId, input);
      throw new ApiError(
        0,
        "offline",
        "Changing somebody's pay needs the API. This writes their employment " +
          "record, and a salary kept in this browser would never reach a real " +
          "payroll.",
      );
    },
    [isConnected],
  );

  const setTaxOverride = useCallback(
    async (
      runId: string,
      input: {
        employeeId: string;
        payeKobo: number;
        reason: string;
        alsoStanding?: boolean;
      },
    ): Promise<TaxOverrideChange> => {
      if (isConnected) return payrollApi.setTaxOverride(runId, input);
      throw new ApiError(
        0,
        "offline",
        "Entering tax by hand needs the API. A figure typed here would recompute " +
          "net pay with no engine to check it against, so the demo will not " +
          "pretend it has.",
      );
    },
    [isConnected],
  );

  /** Clears this period's hand-entered PAYE. Same reasoning as
   *  `setTaxOverride` for why demo mode refuses. */
  const clearTaxOverride = useCallback(
    async (runId: string, employeeId: string): Promise<TaxOverrideChange> => {
      if (isConnected) return payrollApi.clearTaxOverride(runId, employeeId);
      throw new ApiError(
        0,
        "offline",
        "Entering tax by hand needs the API, so there is nothing here for the " +
          "demo to clear.",
      );
    },
    [isConnected],
  );

  return {
    prepare,
    approve,
    cancel,
    exclude,
    putBack,
    setTaxOverride,
    clearTaxOverride,
    setOvertimeOverride,
    clearOvertimeOverride,
    setBonus,
    clearBonus,
    setMonthlyPay,
    connected: isConnected,
  };
}

/* --------------------------------------------------------------- payslips */

export type PayslipRecord = {
  payslip: Payslip | null;
  /**
   * Just enough of the run to place the payslip in time. `PayrollRun` in demo
   * mode (which already has the full run in hand) and `PayslipRunSummary`
   * connected (which now asks for one payslip, not a run) both satisfy this —
   * nothing here reads more than `id`/`period`/`payDate`/`status`.
   */
  run: PayslipRunSummary | null;
  loading: boolean;
  connected: boolean;
  notFound: boolean;
  /**
   * Year-to-date is not available for a single payslip.
   *
   * There is no endpoint for it and summing it would mean fetching every
   * approved run for the year. The demo projects from this month, which it says
   * on screen; connected mode shows nothing rather than a figure somebody might
   * file.
   */
  projectYearToDate: boolean;
};

/**
 * One payslip. `id` is its own id in every real link this app writes; `runId`
 * is now unused for a connected fetch and kept only because demo mode's
 * lookup still benefits from it and `view.tsx` already threads it through.
 *
 * ## Why this used to fetch up to seven runs, and no longer does
 *
 * There was no `GET /payslips/:id` to ask directly, so a connected read
 * fetched the run (with the hint) or searched the newest six runs in turn (a
 * bookmarked link, a payslip mailed out) matching each payslip's own id or its
 * employee id — the latter because the demo's URLs, and every prerendered
 * page, are keyed by employee id. That endpoint exists now, and it settles
 * something the search never could: read as the payslip's own employee, no
 * `VIEW_SALARIES` is required, because it is that employee's own pay. The
 * old path always asked for the whole run and so always needed the
 * permission, which meant an employee could not open their own payslip.
 *
 * Demo mode is unaffected below and keeps matching by either id, since its
 * fixtures and prerendering still use the employee id.
 */
export function usePayslipRecord(
  id: string,
  runId: string | null,
): PayslipRecord {
  const { isConnected } = useSession();
  const demo = useDemoContext();
  const [found, setFound] = useState<{
    id: string;
    payslip: Payslip | null;
    run: PayslipRunSummary | null;
  } | null>(null);

  /* Re-ask when somebody comes back to the window. Not in the key below,
     so the answer is replaced without the screen flashing a skeleton. */
  const revalidation = useRevalidation();
  useEffect(() => {
    if (!isConnected) return;
    let cancelled = false;
    const controller = new AbortController();

    void (async () => {
      try {
        const { payslip, run } = await payrollApi.payslip(
          id,
          controller.signal,
        );
        if (!cancelled) setFound({ id, payslip, run });
      } catch (error) {
        if (error instanceof DOMException && error.name === "AbortError")
          return;
        if (!cancelled) setFound({ id, payslip: null, run: null });
      }
    })();

    return () => {
      cancelled = true;
      controller.abort();
    };
  }, [isConnected, id, revalidation]);

  if (!isConnected) {
    const detail =
      demo.details.find((d) => d.id === runId) ??
      demo.details.find((d) =>
        d.payslips.some((s) => s.id === id || s.employeeId === id),
      ) ??
      null;
    const payslip =
      detail?.payslips.find((s) => s.id === id || s.employeeId === id) ?? null;
    return {
      payslip,
      run: detail ? summarise(detail) : null,
      loading: false,
      connected: false,
      notFound: payslip === null,
      projectYearToDate: true,
    };
  }

  const matched = found !== null && found.id === id;
  return {
    payslip: matched ? found.payslip : null,
    run: matched ? found.run : null,
    loading: !matched,
    connected: true,
    notFound: matched && found.payslip === null,
    projectYearToDate: false,
  };
}

/* --------------------------------------------------------------- utilities */

/** Blockers first, then warnings, then by employee — the order to work through. */
export function orderExceptions(exceptions: RunException[]): RunException[] {
  return [...exceptions].sort((a, b) => {
    if (a.severity !== b.severity) return a.severity === "BLOCKER" ? -1 : 1;
    return a.code.localeCompare(b.code);
  });
}

export const countBySeverity = (exceptions: RunException[]) => ({
  blockers: exceptions.filter((e) => e.severity === "BLOCKER").length,
  warnings: exceptions.filter((e) => e.severity === "WARNING").length,
});
