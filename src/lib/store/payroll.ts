const demoRunId = (period: string) => `demo-${period}`;
const demoPayslipId = (period: string, employeeId: string) =>
  `demo-${period}-${employeeId}`;

/** Naira float → whole kobo. The demo's own rounding boundary. */
const kobo = (naira: number) => Math.round(naira * 100);

/**
 * Which relief regime the fixture's figures were computed under.
 *
 * Read off `DEMO_PAYSLIP_BASIS` rather than assumed, because that block records
 * the schedule the API's engine actually used — currently rent relief, with
 * nothing declared, so every `reliefMonthlyKobo` in the fixture is zero. A
 * payslip that showed that zero under "consolidated relief allowance" would be
 * naming a relief the Nigeria Tax Act 2025 abolished, in the one mode that gets
 * shown to people in rooms with no database.
 *
 * Annotated rather than inferred so a regenerated fixture on the other regime
 * still compiles and still labels itself correctly.
 */
const DEMO_RELIEF: ReliefRegime = DEMO_PAYSLIP_BASIS.schedule.relief;

/**
 * Whether the illustrative figures still describe this company.
 *
 * They were generated on one set of rates, recorded in `DEMO_PAYSLIP_BASIS`.
 * Change the salary split or a pension rate in demo mode and they describe a
 * company that is no longer this one — so the run withholds them and says why,
 * rather than printing figures that contradict the settings screen.
 *
 * `workingDaysPerMonth` is deliberately not compared: the demo run applies no
 * unpaid days, so the divisor cannot move any figure in the fixture. The
 * exception rules are not compared either — they decide what stops a run, not
 * what anybody is paid.
 */
function settingsMatchFixture(settings: PayrollSettings): boolean {
  const basis = DEMO_PAYSLIP_BASIS.settings;
  const sameBasis =
    settings.pension.basis.length === basis.pension.basis.length &&
    basis.pension.basis.every((component) =>
      settings.pension.basis.includes(component),
    );

  return (
    settings.salarySplit.basic === basis.salarySplit.basic &&
    settings.salarySplit.housing === basis.salarySplit.housing &&
    settings.salarySplit.transport === basis.salarySplit.transport &&
    /* The three deduction switches. A fixture generated with PAYE on cannot
       describe a company that has switched it off — every figure below the gross
       line would be a deduction the settings screen says does not happen — so the
       run refuses rather than printing figures that contradict it. */
    settings.paye.enabled === basis.paye.enabled &&
    settings.pension.enabled === basis.pension.enabled &&
    settings.pension.employeeRate === basis.pension.employeeRate &&
    settings.pension.employerRate === basis.pension.employerRate &&
    sameBasis &&
    settings.nhf.enabled === basis.nhf.enabled &&
    settings.nhf.rate === basis.nhf.rate &&
    settings.nhf.basis === basis.nhf.basis
  );
}

/**
 * One demo payslip, in whole kobo, or null.
 *
 * Every statutory figure is read from the fixture — generated by the API's
 * engine, never recomputed here. The only arithmetic is the post-tax deduction,
 * and it is the one piece that needs none: a loan instalment comes off net after
 * PAYE, pension and NHF are settled, so take-home falls by exactly its own
 * amount. Capped at what is there, with the shortfall reported, because a month
 * of unpaid leave is enough to make an instalment unrecoverable and the loan
 * carries the remainder rather than the payslip going negative.
 *
 * Null when the fixture has no row for this salary. The caller turns that into a
 * BLOCKER naming the person; it never becomes a zero, because a zero on a
 * payslip is a claim and this is an absence.
 */
function demoPayslip(
  period: string,
  person: PayrollEmployee,
  figures: DemoPayslipFigures,
): { slip: Payslip; unrecoveredKobo: number } {
  const scheduled = SCHEDULED_DEDUCTIONS.get(person.id);

  const requestedKobo = kobo(scheduled?.amount ?? 0);
  const takenKobo = Math.min(requestedKobo, Math.max(0, figures.netKobo));
  const unrecoveredKobo = requestedKobo - takenKobo;

  const lines: PayslipLine[] = [];
  if (requestedKobo > 0 && scheduled) {
    lines.push({
      id: `${person.id}-deduction`,
      kind: "DEDUCTION",
      label: scheduled.label,
      /* The full instalment, not what fitted. `reconcile.ts` allows the line to
         exceed what was taken precisely so the carried remainder stays visible
         instead of quietly vanishing off the slip. */
      amountKobo: requestedKobo,
      taxable: false,
    });
  }
  lines.push({
    id: `${person.id}-employer-pension`,
    kind: "EMPLOYER_CONTRIBUTION",
    label: "Employer pension",
    amountKobo: figures.pensionEmployerKobo,
    taxable: false,
  });

  return {
    unrecoveredKobo,
    slip: {
      id: demoPayslipId(period, person.id),
      employeeId: person.id,
      employeeNo: person.id.toUpperCase(),
      name: person.name,
      grossKobo: figures.grossKobo,
      basicKobo: figures.basicKobo,
      housingKobo: figures.housingKobo,
      transportKobo: figures.transportKobo,
      pensionEmployeeKobo: figures.pensionEmployeeKobo,
      pensionEmployerKobo: figures.pensionEmployerKobo,
      nhfKobo: figures.nhfKobo,
      taxableIncomeKobo: figures.taxableMonthlyKobo,
      reliefKobo: figures.reliefMonthlyKobo,
      relief: DEMO_RELIEF,
      payeKobo: figures.payeKobo,
      /* Demo payroll is always the fixture's own figures — see the module
         header on why an override cannot exist here without a second engine
         in the browser. */
      payeOverridden: false,
      payeOverrideReason: null,
      otherDeductionsKobo: takenKobo,
      netKobo: figures.netKobo - takenKobo,
      unpaidDays: 0,
      proratedDeductionKobo: 0,
      publishedAt: null,
      emailedAt: null,
      viewedAt: null,
      lines,
    },
  };
}

/**
 * The invariant check, in demo mode.
 *
 * The same identities `approvehr-api/src/modules/payroll/reconcile.ts` asserts,
 * because the gate has to be real in both modes. A demo that renders whatever
 * the arithmetic produced would be demonstrating the incumbent's bug — an
 * audit of the live competitor found a run paying out ₦1.47m more than it cost,
 * displayed without complaint, and the failure was not the arithmetic but that
 * nothing between it and the screen ever asked whether it added up.
 *
 * Exact integer equality, no tolerance. A tolerance is a decision that being
 * slightly wrong is acceptable, and on a payment file it is not.
 */
function reconcileDemo(slips: Payslip[], totals: RunTotalsKobo): Discrepancy[] {
  const found: Discrepancy[] = [];
  const money = (k: number) =>
    (k / 100).toLocaleString("en-NG", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    });

  for (const slip of slips) {
    const taken =
      slip.pensionEmployeeKobo +
      slip.nhfKobo +
      slip.payeKobo +
      slip.otherDeductionsKobo;
    if (slip.netKobo + taken !== slip.grossKobo) {
      found.push({
        code: "net_does_not_reconcile",
        employeeId: slip.employeeId,
        message:
          `Net pay plus deductions comes to ₦${money(slip.netKobo + taken)}, ` +
          `but gross is ₦${money(slip.grossKobo)}.`,
        expectedKobo: slip.grossKobo,
        actualKobo: slip.netKobo + taken,
      });
    }
    if (slip.netKobo > slip.grossKobo) {
      found.push({
        code: "net_exceeds_gross",
        employeeId: slip.employeeId,
        message:
          `Net pay ₦${money(slip.netKobo)} is more than gross ` +
          `₦${money(slip.grossKobo)}. This cannot be right.`,
        expectedKobo: slip.grossKobo,
        actualKobo: slip.netKobo,
      });
    }
    const split = slip.basicKobo + slip.housingKobo + slip.transportKobo;
    if (split !== slip.grossKobo) {
      found.push({
        code: "split_does_not_sum",
        employeeId: slip.employeeId,
        message:
          `Basic plus housing plus transport is ₦${money(split)}, ` +
          `contractual pay is ₦${money(slip.grossKobo)}.`,
        expectedKobo: slip.grossKobo,
        actualKobo: split,
      });
    }
  }

  const fields: [string, number, number][] = [
    ["gross", slips.reduce((t, s) => t + s.grossKobo, 0), totals.grossKobo],
    ["net", slips.reduce((t, s) => t + s.netKobo, 0), totals.netKobo],
    ["PAYE", slips.reduce((t, s) => t + s.payeKobo, 0), totals.payeKobo],
  ];
  for (const [label, expected, actual] of fields) {
    if (expected !== actual) {
      found.push({
        code: "total_does_not_match_payslips",
        message:
          `Total ${label} is ₦${money(actual)} but the payslips add to ` +
          `₦${money(expected)}.`,
        expectedKobo: expected,
        actualKobo: actual,
      });
    }
  }

  return found;
}

type RunTotalsKobo = {
  grossKobo: number;
  netKobo: number;
  payeKobo: number;
  pensionEmployeeKobo: number;
  pensionEmployerKobo: number;
  nhfKobo: number;
};

function totalsOf(slips: Payslip[]): RunTotalsKobo {
  return slips.reduce<RunTotalsKobo>(
    (t, s) => ({
      grossKobo: t.grossKobo + s.grossKobo,
      netKobo: t.netKobo + s.netKobo,
      payeKobo: t.payeKobo + s.payeKobo,
      pensionEmployeeKobo: t.pensionEmployeeKobo + s.pensionEmployeeKobo,
      pensionEmployerKobo: t.pensionEmployerKobo + s.pensionEmployerKobo,
      nhfKobo: t.nhfKobo + s.nhfKobo,
    }),
    {
      grossKobo: 0,
      netKobo: 0,
      payeKobo: 0,
      pensionEmployeeKobo: 0,
      pensionEmployerKobo: 0,
      nhfKobo: 0,
    },
  );
}

/**
 * Demo exceptions, using the API's own codes and severities.
 *
 * Deliberately not `findExceptions` from the frontend engine: that marks a
 * missing pension PIN as *blocking*, and the API treats it as a warning. The
 * demo has to teach what the product actually does, so where the two disagree
 * the API wins and the codes match so a fix link resolves the same way.
 */
function demoExceptions(
  people: PayrollEmployee[],
  slips: Map<string, { slip: Payslip; unrecoveredKobo: number }>,
  settings: PayrollSettings,
  excluded: Map<string, DemoExclusion>,
): RunException[] {
  const out: RunException[] = [];
  const push = (
    severity: RunException["severity"],
    code: string,
    employeeId: string | null,
    message: string,
  ) =>
    out.push({
      id: `${code}-${employeeId ?? "run"}`,
      employeeId,
      severity,
      code,
      message,
    });

  /* Said once, at the top, and never implied away. Every figure on this run is
     output the API's engine produced for the demo salaries — not a live
     calculation, and not one this browser could perform. */
  push(
    "WARNING",
    "demo_illustrative_figures",
    null,
    `These figures are illustrative. They were computed by the payroll engine ` +
      `on the API for ${DEMO_PAYSLIP_BASIS.period} on the demo salaries and are ` +
      `fixed; a real run computes every one of them live. Nothing in this ` +
      `browser calculates PAYE.`,
  );

  /* Settings that no longer match what the figures were generated on. One
     BLOCKER for the run, because every payslip below is affected and repeating
     it per person would bury the reason. */
  if (!settingsMatchFixture(settings)) {
    push(
      "BLOCKER",
      "demo_settings_changed",
      null,
      "These payroll settings are not the ones the demo's illustrative figures " +
        "were computed on, so they no longer describe what this company pays. " +
        "Reset the payroll settings to their defaults, or start the API to see " +
        "figures computed on your own settings.",
    );
  }

  for (const person of people) {
    /**
     * Deliberately left off, so nothing else about them is raised.
     *
     * A WARNING carrying the reason, the decider and the date — the same code
     * and severity the API uses, so a screen written against one works against
     * the other. Not a silent omission: the run has to be able to answer "why
     * was Grace not paid in August?" from its own list of exceptions.
     */
    const left = excluded.get(person.id);
    if (left) {
      const decidedBy = left.decidedBy ? ` by ${left.decidedBy}` : "";
      push(
        "WARNING",
        "excluded_from_payroll",
        person.id,
        /* The trailing full stop is stripped inside the quotes: it would
           double up with the one closing this sentence. Same as the API. */
        `${person.name} is not being paid this period — ` +
          `"${left.reason.replace(/\.$/, "")}". ` +
          `Excluded${decidedBy} on ${left.excludedAt.slice(0, 10)}. They have no ` +
          `payslip on this run and nothing is owed to them by it. They are back ` +
          `on the next period's payroll automatically.`,
      );
      continue;
    }

    const entry = slips.get(person.id);
    if (!entry) {
      /* No illustrative figures for this salary. A blocker rather than a
         silent omission: they are on the payroll and their payslip is missing,
         which is exactly the kind of thing a run must not swallow. */
      push(
        "BLOCKER",
        "demo_no_figures",
        person.id,
        `${person.name} has no payslip in this run. The demo holds illustrative ` +
          `figures only for its own salaries, and theirs is not one of them — ` +
          `statutory deductions are computed by the API and there is no second ` +
          `copy of that arithmetic here. Start the API to pay them.`,
      );
      continue;
    }

    if (settings.exceptions.requireBankAccount && !person.bankAccount) {
      push(
        "BLOCKER",
        "missing_bank_account",
        person.id,
        `${person.name} has no account number. They cannot be paid. ` +
          `Add one, or exclude them from this payroll with a reason.`,
      );
    }
    if (
      settings.exceptions.requirePensionPin &&
      settings.pension.enabled &&
      !person.pensionPin
    ) {
      push(
        "WARNING",
        "missing_pension_pin",
        person.id,
        `${person.name} has no pension PIN. The pension schedule will be incomplete.`,
      );
    }
    if (settings.exceptions.blockNegativeNet && entry.slip.netKobo <= 0) {
      push(
        "BLOCKER",
        "negative_net",
        person.id,
        `${person.name} would be paid nothing this month. Check their deductions.`,
      );
    }
    if (entry.unrecoveredKobo > 0) {
      push(
        "WARNING",
        "deduction_carried",
        person.id,
        `${person.name} earned less than their deductions this month. ` +
          `₦${(entry.unrecoveredKobo / 100).toLocaleString("en-NG", {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
          })} carries forward.`,
      );
    }

    const before = PREVIOUS_NET.get(person.id);
    if (before && before > 0 && !person.joinedThisPeriod) {
      const change = (entry.slip.netKobo / 100 - before) / before;
      if (Math.abs(change) >= settings.exceptions.netSwingThreshold) {
        push(
          "WARNING",
          "net_swing",
          person.id,
          `${person.name}'s net pay is ${change > 0 ? "up" : "down"} ` +
            `${Math.abs(Math.round(change * 100))}% on last month. Confirm that is intended.`,
        );
      }
    }
    if (person.leftThisPeriod) {
      /* `exit_final_pay`, which is the code the API emits for this exact case —
         `leftThisPeriod` is an end date inside the period, and that is
         `exitExceptionsFor`'s `finalMonth` branch in
         `approvehr-api/src/modules/offboarding/service.ts`.

         It used to be `"leaver"`, which was wrong twice over. It is a word this
         product does not use — the vocabulary is "exit" — and no API code has
         ever been called that, so `fixFor()` in `lib/api/payroll.ts` switches on
         a string the connected product never sends. A demo teaching a code that
         does not exist is the one thing this function's header says it must not
         do. */
      push(
        "WARNING",
        "exit_final_pay",
        person.id,
        `${person.name} leaves this period. This is their last payslip — check ` +
          `the final figure and any loan balance before you approve, because ` +
          `there is no next month to correct it in.`,
      );
    }
  }

  return out;
}

/**
 * The settings a demo run computes against.
 *
 * `usePayrollSettings` is localStorage and holds the rates. The **three
 * deduction switches** are not its to answer: the setup wizard writes them into
 * the features store offline, and `GET /payroll/settings` owns them connected.
 * Merged here so one object describes what this company pays, and so
 * `settingsMatchFixture` sees a switched-off deduction as a change like any
 * other and refuses the run.
 *
 * Without this the demo would contradict itself: the wizard would record "we do
 * not deduct PAYE" and the payroll run would keep showing PAYE on every payslip.
 */
function useDemoPayrollSettings(): PayrollSettings {
  const { settings } = usePayrollSettings();
  const answers = useDemoDeductions();
  return useMemo(
    () =>
      answers === null
        ? settings
        : {
            ...settings,
            paye: { enabled: answers.payeEnabled },
            pension: { ...settings.pension, enabled: answers.pensionEnabled },
            nhf: { ...settings.nhf, enabled: answers.nhfEnabled },
          },
    [settings, answers],
  );
}

/**
 * Builds a whole demo run from the live directory.
 *
 * Two people can be in the directory and not in the run: somebody whose salary
 * the fixture has no row for, and everybody at once when the settings have moved
 * away from what the fixture was generated on. Both are BLOCKERs naming the
 * reason — the headcount is the number of payslips there actually are, because a
 * total that counts a payslip it does not have is the incumbent's bug.
 */
function buildDemoRun(
  record: DemoRunRecord,
  people: PayrollEmployee[],
  settings: PayrollSettings,
): PayrollRunDetail {
  const usable = settingsMatchFixture(settings);

  /**
   * The population, split, exactly as `prepare` splits it on the API.
   *
   * `people` is everybody the period covers. Only the ones nobody has excluded
   * get a payslip — and only they raise an exception about their own record,
   * because a blocker about the account number of somebody who is not being paid
   * is a blocker nobody can act on and it would hold every other salary.
   *
   * Intersected with the period's population, so an exclusion recorded for
   * somebody the period no longer covers counts for nothing. The record survives;
   * it just does not claim this run left somebody off who was never on it.
   */
  const excluded = new Map(
    exclusionsOf(record)
      .filter((row) => people.some((person) => person.id === row.employeeId))
      .map((row) => [row.employeeId, row] as const),
  );
  const payable = people.filter((person) => !excluded.has(person.id));

  const computed = new Map(
    payable.flatMap((person) => {
      /* No agreed pay, no payslip — the same rule the API's `prepare` follows,
         where it raises `missing_pay` naming them. This map already omits
         anybody it has no figures for, so the person simply is not on the run. */
      const figures =
        usable && person.grossMonthly !== null
          ? payslipFiguresFor(kobo(person.grossMonthly))
          : null;
      return figures
        ? [[person.id, demoPayslip(record.period, person, figures)] as const]
        : [];
    }),
  );
  const slips = [...computed.values()].map((c) => c.slip);
  const totals = totalsOf(slips);

  const exclusions: RunExclusion[] = [...excluded.values()].flatMap((row) => {
    const person = people.find((p) => p.id === row.employeeId);
    return person
      ? [
          {
            id: `${record.period}-${row.employeeId}`,
            employeeId: row.employeeId,
            employeeNo: row.employeeId.toUpperCase(),
            name: person.name,
            reason: row.reason,
            decidedBy: row.decidedBy,
            excludedAt: row.excludedAt,
          },
        ]
      : [];
  });

  return {
    id: demoRunId(record.period),
    period: record.period,
    payDate: record.payDate,
    status: record.status,
    label: record.label,
    employeeCount: slips.length,
    excludedCount: excluded.size,
    grossKobo: totals.grossKobo,
    netKobo: totals.netKobo,
    payeKobo: totals.payeKobo,
    pensionEmployeeKobo: totals.pensionEmployeeKobo,
    pensionEmployerKobo: totals.pensionEmployerKobo,
    nhfKobo: totals.nhfKobo,
    totalCostKobo: totals.grossKobo + totals.pensionEmployerKobo,
    /* The demo payslips are fixed illustrative rows generated by the API's
       engine on its defaults, which deduct all three. A local switch cannot move
       them, so the demo run must not claim otherwise — `/settings/payroll` says
       the same thing beside the switches. */
    operates: { paye: "DEDUCTED", pension: "DEDUCTED", nhf: "DEDUCTED" },
    preparedAt: record.preparedAt,
    approvedAt: record.approvedAt,
    paidAt: null,
    settingsFrozen: false,
    payslips: slips,
    exceptions: demoExceptions(people, computed, settings, excluded),
    exclusions,
    /* Entering PAYE by hand needs the same engine the figures themselves
       came from, so it is refused in demo mode outright — see
       `usePayrollActions().setTaxOverride`. Nothing here can ever be
       overridden, so the list is always empty. */
    taxOverrides: [],
  };
}

/**
 * The `PreparedRun` shape, from a demo run that has just been built.
 *
 * One place, because three demo actions answer with it — prepare, exclude and
 * put back — and each one has to report the same figures the screen will read
 * back out of the run itself. `excluded` is beside `headcount` rather than
 * inside it: a caller has to be able to say "9 of 10 — 1 excluded".
 */
const preparedFrom = (detail: PayrollRunDetail): PreparedRun => ({
  runId: detail.id,
  headcount: detail.employeeCount,
  excluded: detail.excludedCount,
  discrepancies: reconcileDemo(detail.payslips, totalsOf(detail.payslips)),
  blockers: detail.exceptions.filter((e) => e.severity === "BLOCKER").length,
  warnings: detail.exceptions.filter((e) => e.severity === "WARNING").length,
});

/** The frozen snapshot wins whenever there is one. That is the one-way door. */
const resolveDemoRun = (
  record: DemoRunRecord,
  people: PayrollEmployee[],
  settings: PayrollSettings,
): PayrollRunDetail => record.frozen ?? buildDemoRun(record, people, settings);

const summarise = (detail: PayrollRunDetail): PayrollRun => {
  const { payslips, exceptions, exclusions, ...run } = detail;
  void payslips;
  void exceptions;
  void exclusions;
  return run;
};

